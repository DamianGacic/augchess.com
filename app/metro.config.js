// The app runs the same rules as the server: it imports ../engine, ../chess.js
// and ../data.js straight from the repo, so Metro watches the repo root (minus
// the web/server builds and their node_modules).
//
// Static art and augment descriptions live in the repo's augments/ and
// figures/ folders. Metro can only bundle a require() written out literally,
// so each start regenerates src/generated/assets.js listing every file.
const fs = require('fs');
const path = require('path');
const { getDefaultConfig } = require('expo/metro-config');

const appRoot = __dirname;
const repoRoot = path.resolve(appRoot, '..');

function writeAssetIndex() {
  const out = path.join(appRoot, 'src/generated');
  fs.mkdirSync(out, { recursive: true });
  const list = dir => fs.readdirSync(path.join(repoRoot, dir)).filter(f => !f.startsWith('.')).sort();
  const requires = (dir, ext) => list(dir)
    .filter(f => f.endsWith(ext))
    .map(f => `  ${JSON.stringify(f.slice(0, -ext.length))}: require('../../../${dir}/${f}'),`)
    .join('\n');
  const descriptions = Object.fromEntries(list('augments/descriptions')
    .filter(f => f.endsWith('.txt'))
    .map(f => [f.slice(0, -4), fs.readFileSync(path.join(repoRoot, 'augments/descriptions', f), 'utf8').trim()]));
  fs.writeFileSync(path.join(out, 'assets.js'), `// Generated by metro.config.js on every start — don't edit.
export const augmentIcons = {
${requires('augments/icons', '.svg')}
};
export const figureIcons = {
${requires('figures/icons', '.svg')}
};
export const figureImages = {
${requires('figures/images', '.png')}
${requires('figures/images', '.svg')}
};
export const descriptions = ${JSON.stringify(descriptions, null, 2)};
`);
}
writeAssetIndex();

const config = getDefaultConfig(appRoot);
config.watchFolders = [repoRoot];
const escape = p => path.join(repoRoot, p).replace(/[/\\]/g, '[/\\\\]');
config.resolver.blockList = [
  ...[].concat(config.resolver.blockList || []),
  ...['node_modules', 'server', 'dist', 'old_design', 'context', 'src', 'supabase', 'tools']
    .map(p => new RegExp(`^${escape(p)}([/\\\\].*)?$`)),
];
// The app's own packages, even for files under the repo root.
config.resolver.nodeModulesPaths = [path.join(appRoot, 'node_modules')];

module.exports = config;
